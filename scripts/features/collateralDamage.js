function addCollateralDamageEditorTabs(app, html) {
	const root = html?.[0] ?? html;
	const form = root?.querySelector?.(
		`.rule-element-forms .rule-form[data-key="${RULE_KEY}"]`
	);
	const container = form?.querySelector(".container.autogenerated");
	if (!container || container.dataset.vursTabbed === "true") return;

	const tabDefinitions = [
		{ key: "general", label: "General", fields: ["value", "type", "distance", "within", "selector", "predicate"] },
		{ key: "area", label: "Area", fields: ["width", "affects", "affectsSelf", "divided", "areaDamage", "placement"] },
		{ key: "damage", label: "Damage", fields: ["collateralDamageThreshold", "mode", "beforeReduction", "damageType"] },
		{ key: "bounce", label: "Bounce", fields: ["bounceShots", "bounceCount", "bounceLimit", "bounceNearest"] }
	];
	const fieldTabs = new Map(tabDefinitions.flatMap(tab =>
		tab.fields.map(field => [field, tab.key])
	));
	const tabs = document.createElement("nav");
	tabs.className = "vurs-collateral-damage-tabs";
	tabs.setAttribute("role", "tablist");

	const panels = new Map();
	const buttons = new Map();
	for (const tab of tabDefinitions) {
		const button = document.createElement("button");
		button.type = "button";
		button.className = "vurs-collateral-damage-tab";
		button.setAttribute("role", "tab");
		button.dataset.vursCollateralTab = tab.key;
		button.textContent = localizeRuleElementFormText(
			`CollateralDamage.Tabs.${tab.label}`,
			tab.label
		);
		tabs.append(button);
		buttons.set(tab.key, button);

		const panel = document.createElement("div");
		panel.className = "vurs-collateral-damage-panel";
		panel.setAttribute("role", "tabpanel");
		panel.dataset.vursCollateralPanel = tab.key;
		panels.set(tab.key, panel);
	}

	for (const fieldGroup of [...container.children]) {
		const field = fieldGroup.querySelector?.("[name]")?.name?.split(".").at(-1);
		const tab = panels.get(fieldTabs.get(field) ?? "general");
		tab?.append(fieldGroup);
	}

	const typeInput = container.querySelector('[name$=".type"]');
	const bounceButton = buttons.get("bounce");
	let activeTab = "general";
	const activateTab = key => {
		if (key === "bounce" && typeInput?.value !== "bounce") key = "general";
		activeTab = key;
		for (const [tabKey, button] of buttons) {
			const active = tabKey === activeTab;
			button.classList.toggle("active", active);
			button.setAttribute("aria-selected", String(active));
			panels.get(tabKey).hidden = !active;
		}
	};
	for (const [key, button] of buttons) {
		button.addEventListener("click", () => activateTab(key));
	}
	const updateBounceTab = () => {
		const isBounce = typeInput?.value === "bounce";
		bounceButton.hidden = !isBounce;
		if (!isBounce && activeTab === "bounce") activateTab("general");
	};
	typeInput?.addEventListener("change", updateBounceTab);

	container.before(tabs);
	for (const tab of tabDefinitions) container.append(panels.get(tab.key));
	container.dataset.vursTabbed = "true";
	updateBounceTab();
	activateTab("general");
}

