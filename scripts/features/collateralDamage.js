async function createCollateralDamageCard(damageParams, effect, secret) {
	const damageRoll = damageParams.damage;
	if (typeof damageRoll?.toMessage !== "function") {
		console.error(`${MODULE_ID} | Could not create a ${RULE_KEY} damage card: DamageRoll.toMessage is unavailable`);
		ui.notifications.error(`Could not create a ${RULE_KEY} damage card.`);
		return;
	}

	let whisper;
	if (secret) {
		whisper = ChatMessage.getWhisperRecipients("GM").map(user => user.id);
		if (!whisper.length) {
			console.error(`${MODULE_ID} | Could not create a private ${RULE_KEY} damage card: no GM recipients are available`);
			ui.notifications.error(`Could not send the private ${RULE_KEY} damage card to a GM.`);
			return;
		}
	}

	const item = damageParams.item;
	const sourceActor = damageParams.vursDamageDealer ?? item?.actor ?? item?.parent ?? null;
	const systemFlags = {
		context: {
			type: "damage-roll",
			options: [
				...(damageParams.rollOptions instanceof Set
					? damageParams.rollOptions
					: Array.isArray(damageParams.rollOptions) ? damageParams.rollOptions : [])
			]
		}
	};
	if (item?.uuid || sourceActor?.uuid) {
		systemFlags.origin = {
			...(item?.uuid ? { uuid: item.uuid } : {}),
			...(sourceActor?.uuid ? { actor: sourceActor.uuid } : {})
		};
	}

	await damageRoll.toMessage({
		speaker: ChatMessage.getSpeaker(sourceActor ? { actor: sourceActor } : {}),
		flavor: `${effect.label}: ${effect.targetName}`,
		...(secret ? { whisper, blind: true } : {}),
		flags: {
			[game.system.id]: systemFlags,
			[MODULE_ID]: { collateralDamageCard: true }
		}
	});
}

function prepareCollateralDamageForTarget(
	target,
	amount,
	damageRollSource,
	damageType,
	sourceLabel,
	sourceParams,
	areaDamage
) {
	const damageRoll = createCollateralDamageRoll(amount, damageRollSource, damageType);
	if (!damageRoll) return null;
	if (typeof target.actor.applyDamage !== "function") {
		console.error(`${MODULE_ID} | Could not apply ${RULE_KEY} to ${target.name}: the Actor applyDamage method is unavailable`);
		return null;
	}

	const secret = target.hidden || target.object?.isVisible === false;
	const sourceRollOptions = sourceParams.rollOptions instanceof Set
		? sourceParams.rollOptions
		: Array.isArray(sourceParams.rollOptions) ? sourceParams.rollOptions : [];
	const rollOptions = new Set([
		...sourceRollOptions,
		...(target.actor.getSelfRollOptions?.() ?? [])
	]);
	rollOptions.delete("area-damage");
	rollOptions.delete("item:area-damage");
	if (areaDamage) rollOptions.add("area-damage");
	const modifiers = getDamageModifierBreakdown(
		damageRollSource,
		sourceParams.vursDamageModifiers
	);
	const damageParams = {
		damage: damageRoll,
		token: target.object ?? target,
		item: getDamageSourceItem(sourceParams),
		rollOptions,
		vursDamageModifiers: modifiers
	};
	const effect = {
		type: "collateral",
		label: sourceLabel,
		amount,
		targetName: target.name,
		hidden: secret,
		modifiers
	};
	return { actor: target.actor, damageParams, effect, secret, targetName: target.name };
}

